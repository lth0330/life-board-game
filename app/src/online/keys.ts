const CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ'
const JUNG = 'ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ'
const JONG = ['', ...'ㄱㄲㄳㄴㄵㄶㄷㄹㄺㄻㄼㄽㄾㄿㅀㅁㅂㅄㅅㅆㅇㅈㅊㅋㅌㅍㅎ']
export const hangulToKeys = (v: string) => [...v].map((ch) => {
  const c = ch.charCodeAt(0) - 0xac00
  if (c >= 0 && c < 11172) {
    const jamo = CHO[Math.floor(c / 588)] + JUNG[Math.floor((c % 588) / 28)] + JONG[c % 28]
    return [...jamo].map((j) => JAMO_KEY[j]).join('')
  }
  return JAMO_KEY[ch] ?? ch
}).join('')
