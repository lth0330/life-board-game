export function Manual({ onClose }: { onClose: () => void }) {
  const [i, setI] = useState(0)
  return (
    <Sheet title="게임 설명서" onClose={onClose}>
      <div className="tabs manual-tabs" role="tablist">
        {PAGES.map((p, k) => (
          <button key={p.title} role="tab" aria-selected={i === k} className={i === k ? 'on' : ''} onClick={() => setI(k)}>{p.title}</button>
        ))}
      </div>
      <div className="manual-body">{PAGES[i].body}</div>
      <div className="row">
        <button className="grow" disabled={i === 0} onClick={() => setI(i - 1)}>이전</button>
        <button className="grow" disabled={i === PAGES.length - 1} onClick={() => setI(i + 1)}>다음</button>
      </div>
    </Sheet>
  )
}
